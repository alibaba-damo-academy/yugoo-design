import {chromium} from 'playwright'
import assert from 'node:assert/strict'
const browser=await chromium.launch({headless:true,args:['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']})
try{
  const page=await browser.newPage({viewport:{width:1400,height:1000}}),errors=[]
  page.on('pageerror',e=>errors.push(e.stack))
  await page.goto('http://127.0.0.1:40169/?real')
  await page.getByRole('button',{name:/^视图与筛选/}).click()
  await page.selectOption('[aria-label="布局视角"]','source')
  await page.getByRole('button',{name:'关闭视图设置'}).click()
  await page.waitForSelector('svg[data-layout-state="settled"]')
  const node=page.locator('g[data-node-id]').first(),before=await node.getAttribute('transform')
  const point=await node.evaluate(el=>{const p=new DOMPoint(0,0).matrixTransform(el.getScreenCTM());return{x:p.x,y:p.y}})
  await page.mouse.move(point.x,point.y);await page.mouse.down();await page.mouse.move(point.x+70,point.y+45,{steps:12});await page.mouse.up()
  assert.equal(await node.getAttribute('data-pinned'),'true')
  const after=await node.getAttribute('transform');assert.notEqual(after,before)
  await page.waitForTimeout(500);assert.equal(await node.getAttribute('transform'),after)
  const radii=()=>page.locator('g[data-node-id] > circle:first-child').evaluateAll(els=>els.map(el=>el.getAttribute('r')))
  const uniform=await radii()
  await page.getByRole('button',{name:/^视图与筛选/}).click()
  await page.selectOption('[aria-label="节点大小"]','reach')
  await page.getByRole('button',{name:'关闭视图设置'}).click()
  assert.notDeepEqual(await radii(),uniform)
  assert.equal(await node.getAttribute('transform'),after)
  assert.equal(await node.getAttribute('data-pinned'),'true')
  await page.getByRole('button',{name:/^视图与筛选/}).click()
  await page.selectOption('[aria-label="节点大小"]','uniform')
  await page.getByRole('button',{name:'关闭视图设置'}).click()
  assert.deepEqual(await radii(),uniform)
  await page.getByText('解除固定并重新布局',{exact:true}).click()
  await page.waitForSelector('svg[data-layout-state="settled"]')
  assert.equal(await node.getAttribute('data-pinned'),null)
  await page.getByRole('button',{name:/^视图与筛选/}).click()
  await page.selectOption('[aria-label="图谱布局"]','stress3')
  await page.getByRole('button',{name:'关闭视图设置'}).click()
  await page.waitForSelector('[aria-label="三维关联图"][data-layout-state="settled"]')
  for(const projection of ['perspective','orthographic']){
  await page.selectOption('[aria-label="三维投影"]',projection)
  await page.waitForTimeout(250)
  await page.waitForSelector('[data-node-x]')
  const host=page.locator('[aria-label="三维关联图"]'),box=await host.boundingBox()
  const candidates=await page.locator('[data-node-x]').evaluateAll(els=>els.map(el=>({id:el.dataset.nodeId,x:+el.dataset.nodeX,y:+el.dataset.nodeY})))
  let pinned=false
  for(const p of candidates){
    await page.mouse.move(box.x+p.x,box.y+p.y);await page.mouse.down();await page.mouse.move(box.x+p.x+55,box.y+p.y+30,{steps:15});await page.mouse.up()
    if(await host.getAttribute('data-last-pinned')){pinned=true;break}
  }
  assert.ok(pinned,'3D sphere drag must invoke pin handler')
  const pin=await host.getAttribute('data-last-pinned')
  await host.locator('canvas').evaluate(el=>el.dataset.sizeTest='preserved')
  await page.getByRole('button',{name:/^视图与筛选/}).click()
  await page.selectOption('[aria-label="节点大小"]','reach')
  await page.getByRole('button',{name:'关闭视图设置'}).click()
  assert.equal(await host.getAttribute('data-last-pinned'),pin)
  assert.equal(await host.locator('canvas').getAttribute('data-size-test'),'preserved')
  await page.getByRole('button',{name:/^视图与筛选/}).click()
  await page.selectOption('[aria-label="节点大小"]','uniform')
  await page.getByRole('button',{name:'关闭视图设置'}).click()
  await page.getByText('解除固定并重新布局',{exact:true}).click()
  await page.waitForSelector('[aria-label="三维关联图"][data-layout-state="settled"]')
  }
  assert.deepEqual(errors,[])
  console.log('PASS: source Stress, 2D drag stays pinned/reset, 3D drag pin/reset, no browser errors')
}finally{await browser.close()}
