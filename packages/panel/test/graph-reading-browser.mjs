/** Read-only, bounded acceptance on a frozen experimental page, not production KAG. */
import {chromium} from 'playwright'
import {readFile,writeFile} from 'node:fs/promises'
import {dirname,join} from 'node:path'
import {pathToFileURL} from 'node:url'
import assert from 'node:assert/strict'
const path=process.argv[2],out=dirname(path),source=JSON.parse((await readFile(path,'utf8')).match(/<script id="graph-data" type="application\/json">([\s\S]*?)<\/script>/)[1])
const browser=await chromium.launch({headless:true}),errors=[],report={}
try{
  const page=await browser.newPage({viewport:{width:1500,height:980}})
  page.on('pageerror',e=>errors.push(String(e)))
  await page.goto(pathToFileURL(path).href)
  const settled=()=>page.waitForFunction(()=>graphExperiment.snapshot().stopped,{},{timeout:15000})
  const snap=()=>page.evaluate(()=>graphExperiment.snapshot())
  const coords=s=>s.nodes.map(n=>[n.id,n.x,n.y])
  await settled();await page.waitForTimeout(100)
  assert.equal((await snap()).algorithm,'fCoSE')
  const original=await snap()
  // This sample has a root whose relations mostly live on children.
  await page.getByRole('button',{name:'文献精读与关联发现',exact:true}).click()
  const selected=await snap(),id=selected.selected
  assert.equal(selected.relatedRecords.length,8)
  assert.equal(await page.locator('.relation-choice').count(),8)
  assert.deepEqual(coords(selected),coords(original))
  assert.deepEqual(selected.camera,original.camera)
  assert.ok(selected.relatedRecords.every(id=>selected.highlightedNodes.includes(id)))
  await page.screenshot({path:join(out,'reading-overview.png')})
  const related=source.nodes.find(n=>n.record&&n.label==='深度阅读与笔记')
  await page.locator('.relation-choice').filter({hasText:'深度阅读与笔记'}).click()
  let state=await snap()
  assert.equal(state.targetRecord,related.id)
  const evidence=page.locator('.evidence-choice').first(),edgeId=await evidence.getAttribute('data-edge')
  await evidence.click();state=await snap()
  assert.equal(state.selectedEvidence,edgeId)
  assert.ok(state.highlightedEdges.includes(edgeId))
  assert.equal(await page.locator('.evidence-card.chosen .endpoint-text').count(),2)
  assert.match(await page.locator('.evidence-card.chosen').innerText(),/不是因果、依赖/)
  assert.deepEqual(coords(state),coords(original))
  await page.getByRole('button',{name:'下一处',exact:true}).click()
  assert.notEqual((await snap()).selectedEvidence,edgeId)
  assert.deepEqual(coords(await snap()),coords(original))
  await page.getByRole('button',{name:'上一处',exact:true}).click()
  assert.equal((await snap()).selectedEvidence,edgeId)
  await page.locator('#expanded').click();await settled()
  state=await snap()
  assert.equal(state.selected,id);assert.equal(state.selectedEvidence,edgeId)
  assert.equal(state.targetRecord,related.id)
  assert.equal(state.nodes.length,source.nodes.length);assert.equal(state.edges,source.edges.length)
  // An explicit view-mode change now fits all newly visible nodes; selection
  // itself still never changes geometry or camera (assertions above).
  const canvas=await page.locator('#graph').boundingBox()
  assert.ok(state.nodes.every(n=>n.screen.x>=0&&n.screen.x<=canvas.width&&n.screen.y>=0&&n.screen.y<=canvas.height))
  const raw=source.edges.find(e=>e.id===edgeId)
  assert.ok(state.highlightedNodes.includes(raw.from)&&state.highlightedNodes.includes(raw.to))
  await page.locator('#fit').click();await page.waitForTimeout(450)
  await page.screenshot({path:join(out,'reading-evidence-expanded.png')})
  // Moving the mouse over another node must not steal the pinned reading selection.
  const host=await page.locator('#graph').boundingBox(),beforeHover=await snap()
  const other=beforeHover.nodes.find(n=>n.record&&n.id!==id&&n.screen.x>20&&n.screen.x<host.width-20&&n.screen.y>20&&n.screen.y<host.height-20)
  await page.mouse.move(host.x+other.screen.x,host.y+other.screen.y);await page.waitForTimeout(100)
  assert.equal((await snap()).selectedEvidence,edgeId)
  assert.deepEqual((await snap()).highlightedEdges,beforeHover.highlightedEdges)
  await page.mouse.move(5,5)
  await page.locator('#overview').click();await settled()
  assert.equal((await snap()).selectedEvidence,edgeId)
  await page.getByRole('button',{name:'以这条记录为中心',exact:true}).click()
  assert.equal((await snap()).selected,related.id)
  await page.getByRole('button',{name:'清除选择',exact:true}).click()
  assert.equal((await snap()).selected,'')
  // Actual canvas node selection (not a test-only selection API).
  await page.locator('#fit').click();await page.waitForTimeout(450)
  const current=await snap(),point=current.nodes.find(n=>n.id===id),bounds=await page.locator('#graph').boundingBox()
  await page.mouse.move(bounds.x+point.screen.x,bounds.y+point.screen.y)
  await page.waitForFunction(id=>graphExperiment.snapshot().hovered===id,id)
  await page.mouse.click(bounds.x+point.screen.x,bounds.y+point.screen.y)
  await page.waitForFunction(id=>graphExperiment.snapshot().selected===id,id)
  assert.equal((await snap()).selected,id)
  await page.mouse.move(5,5)
  const camera=(await snap()).camera
  await page.locator('#search').fill('文献');assert.deepEqual((await snap()).camera,camera)
  await page.locator('#search').fill('')
  await page.setViewportSize({width:680,height:900});await page.locator('#fit').click();await page.waitForTimeout(450)
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
  assert.ok((await page.locator('#graph').boundingBox()).height>=300)
  assert.ok((await page.locator('footer').boundingBox()).height>=200)
  await page.screenshot({path:join(out,'reading-narrow.png')})
  state=await snap();assert.ok(state.sourceUnchanged);assert.deepEqual(errors,[])
  Object.assign(report,{checkpoint:source.checkpoint,nodes:source.nodes.length,edges:source.edges.length,relatedRecords:8,selectionAcrossViews:true,selectionDoesNotRelayout:true,rawEndpointsHighlighted:true,canvasClick:true,narrow:true,sourceUnchanged:state.sourceUnchanged,errors})
}finally{await browser.close()}
await writeFile(join(out,'reading-verification.json'),JSON.stringify(report,null,2));console.log(JSON.stringify(report))
