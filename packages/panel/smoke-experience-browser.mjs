  await checkExperienceFooter()
  const directory = page.getByRole('navigation', { name: '场景目录', exact: true })
  assert.equal(await page.getByRole('combobox', { name: '选择场景体验' }).count(), 0)
  assert.ok((await directory.boundingBox()).x + (await directory.boundingBox()).width <= (await page.locator('iframe').boundingBox()).x, 'Desktop directory sits to the left of the experience')
  assert.equal(await page.locator('.dsh-experience-evidence').getAttribute('open'), null)
