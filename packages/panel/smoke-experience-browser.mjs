/** Browser proof of the real workspace/system panel; isolated host transport, no model calls. */
import assert from 'node:assert/strict'
import { execFile } from 'node:child_process'
import { promisify } from 'node:util'
import { createServer } from 'node:http'
import { mkdtemp, readFile, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { chromium } from 'playwright'
const exec = promisify(execFile), root = import.meta.dirname, out = await mkdtemp(join(tmpdir(), 'experience-browser-'))
// Independent Chromium: the local agent-browser CDP session can leave sandboxed
// srcdoc documents without a layout viewport. Never weaken the production sandbox.
const chromiumBrowser = await chromium.launch({ headless: true })
const page = await chromiumBrowser.newPage({ locale: 'zh-CN', viewport: { width: 1200, height: 860 } })
const browser = async (command, ...args) => {
  if (command === 'open') return page.goto(args[0])
  if (command === 'set') return page.setViewportSize({ width: Number(args[1]), height: Number(args[2]) })
  if (command === 'wait') return args[0] === '--fn' ? page.waitForFunction(args[1]) : page.locator(args[0]).waitFor()
  if (command === 'eval') return page.evaluate(args[0])
  if (command === 'screenshot') return page.screenshot({ path: args[0] })
  if (command === 'close') return chromiumBrowser.close()
  if (command === 'snapshot') return page.locator('body').innerText()
  throw new Error(`Unsupported test operation: ${command}`)
}
const click = name => page.getByRole('button', { name, exact: true }).click()
const check = async code => assert.equal(await page.evaluate(code), true, code)
