import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'

const script = new URL('../bundles/design_style/scripts/design-style.mjs', import.meta.url)
function run(action, input) {
  return spawnSync(process.execPath, [script.pathname, action], { input, encoding: 'utf8', maxBuffer: 8 * 1024 * 1024 })
}

const state = { config: {
  theme: 'Academic workspace', colors: { primary: '#2457d6', background: '#f7f8fa' },
  semantic_colors: {}, typography: {}, components: { borderRadius: '8px', shadowDepth: 'subtle' }, layout: { density: 'comfortable' },
  hierarchy: { page_title: 'Primary screen identity' },
  component_patterns: { navigation: { description: 'Shared navigation', anatomy: ['icon', 'label'], states: ['default', 'active'] } },
  iconography: { library: 'bundled', style: 'outline', stroke_width: '1.75' },
  icons: { navigation_search: { label: 'Search', svg: '<svg viewBox="0 0 24 24"><circle cx="11" cy="11" r="8"/></svg>', asset: 'assets/icons/search.svg' } },
  brand: { name: 'Research Desk', mark_id: 'primary', mark_svg: '<svg viewBox="0 0 24 24"><path d="M4 4h16v16H4z"/></svg>' },
  preview_page: { name: 'workspace', title: 'Workspace', rationale: 'Representative research screen', html_file: 'design_style/preview_workspace.html' },
} }
const html = '<html><head><link rel="stylesheet" href="./tokens.css"></head><body style="color:var(--ds-text);background:var(--ds-background);font-family:var(--ds-body-font);border:1px solid var(--ds-border);border-radius:var(--ds-radius)"><svg aria-label="Search"></svg></body></html>'
const designMd = run('render-design-md', JSON.stringify(state))
const tokensCss = run('render-tokens-css', JSON.stringify(state))
assert.equal(designMd.status, 0, designMd.stderr || designMd.stdout)
assert.equal(tokensCss.status, 0, tokensCss.stderr || tokensCss.stdout)
assert.match(designMd.stdout, /## Overview/)
assert.match(designMd.stdout, /## brand/)
assert.match(designMd.stdout, /"mark_id": "primary"/)
assert.match(tokensCss.stdout, /--ds-primary: #2457d6/)
assert.match(tokensCss.stdout, /--ds-font-size-2xl: 28px/)
assert.match(tokensCss.stdout, /--ds-icon-stroke-width: 1.75/)
const tokenContext = `${JSON.stringify({ state })}\n`
assert.equal(run('validate-tokens-file', tokenContext + tokensCss.stdout).status, 0)
const divergent = run('validate-tokens-file', tokenContext + ':root{--ds-font-main:Arial;--ds-fill-4:white}')
assert.equal(divergent.status, 1)
assert.match(divergent.stdout, /regenerate it with render-tokens-css/)
const changedState = structuredClone(state)
changedState.config.colors.primary = '#123456'
assert.equal(run('validate-tokens-file', `${JSON.stringify({ state: changedState })}\n${tokensCss.stdout}`).status, 1,
  'old generated bytes cannot pass against a new canonical config')
assert.doesNotMatch(tokensCss.stdout, /navigation_search|data:image/)
const context = `${JSON.stringify({ state, preview_file: 'design_style/preview_workspace.html' })}\n`
const validated = run('validate-preview-file', `${context}${html}`)
assert.equal(validated.status, 0, validated.stderr || validated.stdout)
assert.equal(JSON.parse(validated.stdout).valid, true)
assert.equal(run('validate-preview-file', `${context}${html.replace('var(--ds-radius)', '8px')}`).status, 1)
const rawPreview = html.replace('</head>', '<style>.bad{padding:12px;margin:18px;font-size:20px;line-height:1.4;border-radius:10px}</style></head>')
const rawResult = run('validate-preview-file', `${context}${rawPreview}`)
assert.equal(rawResult.status, 1)
const rawMessages = JSON.parse(rawResult.stdout).diagnostics.join('\n')
assert.match(rawMessages, /padding: 12px; margin: 18px/)
assert.match(rawMessages, /font-size: 20px/)
const invalidAuthority = structuredClone(state)
invalidAuthority.config.brand.mark_svg = 'not svg'
invalidAuthority.config.icons.navigation_search.svg = 'not svg'
const invalidContext = `${JSON.stringify({ state: invalidAuthority, preview_file: 'design_style/preview_workspace.html' })}\n`
const invalidResult = run('validate-preview-file', `${invalidContext}${html}`)
assert.equal(invalidResult.status, 1)
const invalidMessages = JSON.parse(invalidResult.stdout).diagnostics.join('\n')
assert.match(invalidMessages, /brand\.mark_svg must be one safe complete SVG/)
assert.match(invalidMessages, /icons\.navigation_search\.svg must be one safe complete SVG/)
const textOnlyState = structuredClone(state)
textOnlyState.config.brand = { name: 'Research Desk' }
const textOnlyContext = `${JSON.stringify({ state: textOnlyState, preview_file: 'design_style/preview_workspace.html' })}\n`
const textOnlyResult = run('validate-preview-file', `${textOnlyContext}${html}`)
assert.equal(textOnlyResult.status, 0, textOnlyResult.stderr || textOnlyResult.stdout)

// Existing raster brand fields do not require manufacturing an SVG counterpart.
const rasterState = structuredClone(textOnlyState)
rasterState.config.brand.logo_image = { source: 'external', path: 'design_style/images/logo.png', alt: 'Original logo' }
const rasterHtml = html.replace('</body>', '<img src="./images/logo.png" alt="Original logo"></body>')
const rasterResult = run('validate-preview-file', `${JSON.stringify({ state: rasterState, preview_file: 'design_style/preview_workspace.html' })}\n${rasterHtml}`)
assert.equal(rasterResult.status, 0, rasterResult.stdout || rasterResult.stderr)
assert.match(run('render-design-md', JSON.stringify(rasterState)).stdout, /design_style\/images\/logo.png/u)

console.log('DESIGN STYLE AGENT SCRIPT OK')
