import React, {
  useCallback,
  useEffect,
  useMemo,
  useRef,
  useState,
} from 'react';
import {
  ResizablePanelGroup,
  ResizablePanel,
  ResizableHandle,
} from '../../ui/resizable.tsx';
import { Button } from '../../ui/button.tsx';
import type {
  IDesignStylePanel as IDesignStylePanelData,
  IDesignStyleConfig,
  ILayoutConfig,
} from './designStyleTypes.ts';
import {
  PALETTE_PRESETS,
  AI_PRESET_ID,
  applyPaletteToConfig,
  buildAiPreset,
  type IPalettePreset,
} from './presetThemes.ts';
import { PresetThemesNav } from './PresetThemesNav.tsx';
import { PreviewFrame } from './PreviewFrame.tsx';
import {
  DEFAULT_FINE_TUNE_OPEN_SECTIONS,
  FineTuneOverlay,
  type IFineTuneOpenSections,
} from './FineTuneOverlay.tsx';
import { IconFont } from '../../ui/icon-font.tsx';
import { EllipsisTooltip } from '../../ui/ellipsis-tooltip.tsx';
import { useLang } from '../../host.ts';
import { DesignPanelHeader, DesignPanelTitle } from '../OfficialWebAppPanels/panelPrimitives.tsx';
import { useDesignLeftPanelSizes } from '../panelSizing.ts';

export interface IDesignStylePanelProps {
  data: IDesignStylePanelData;
  /** When provided, edits propagate via this callback (typically wired to
   *  `updateDesignPanel` in the design store). When omitted, panel is
   *  read-only. */
  onChange?: (updates: Partial<IDesignStylePanelData>) => void;
  onSaveAndRegenerate?: () => void;
  onRefresh?: () => void;
  disabled?: boolean;
}

const DEFAULT_LAYOUT: ILayoutConfig = {
  mode: 'sidebar',
  sidebar: { position: 'left', style: 'fixed' },
  content_width: 'wide',
  density: 'comfortable',
};

/**
 * Make sure the config we hand off to the preview/editors always has a
 * `layout` object. Belt-and-suspenders for the schema migration.
 */
const normalizeConfig = (
  config: IDesignStyleConfig | null
): IDesignStyleConfig => {
  if (!config) {
    return {
      theme: '',
      layout: DEFAULT_LAYOUT,
      colors: {},
      typography: {},
      components: {},
      semantic_colors: {},
      notes: '',
    };
  }
  const layout =
    config.layout && typeof config.layout === 'object'
      ? (config.layout as ILayoutConfig)
      : DEFAULT_LAYOUT;
  return { ...config, layout };
};

/**
 * Design style panel — three regions:
 *   - Left:  palette presets (one click swaps colors, keeps layout/etc).
 *   - Center: live preview rendered in an iframe; the iframe content is
 *             a bespoke prototype HTML+JS page generated by the design
 *             style skill from the project's actual context.
 *   - Right (overlay): fine-tune editor — opens via "微调", layered over
 *             the preview as a sliding sheet.
 *
 * Save flow mirrors smart_questions / function_modules: every edit pushes
 * via `onChange` → store → `hasDesignStylePanelChanges` → red dot on tab
 * → user clicks Save in the parent footer to flush to backend.
 */
export const DesignStylePanel: React.FC<IDesignStylePanelProps> = ({
  data,
  onChange,
  onSaveAndRegenerate,
  onRefresh,
  disabled,
}) => {
  const t = useLang();
  const splitContainerRef = useRef<HTMLDivElement>(null);
  const leftPanelSizes = useDesignLeftPanelSizes(splitContainerRef);

  const [tuneOpen, setTuneOpen] = useState(false);
  const [fineTuneOpenSections, setFineTuneOpenSections] =
    useState<IFineTuneOpenSections>(DEFAULT_FINE_TUNE_OPEN_SECTIONS);
  const [fineTuneActiveColor, setFineTuneActiveColor] = useState<string | null>(
    'primary'
  );
  const [aiPaletteActive, setAiPaletteActive] = useState(() => {
    const theme = data.config?.theme;
    if (!theme) return true;
    return !PALETTE_PRESETS.some(p => p.name === theme || p.id === theme);
  });
  const config = useMemo(() => normalizeConfig(data.config), [data.config]);

  useEffect(() => {
    const theme = data.config?.theme;
    if (!theme) return;
    const isPreset = PALETTE_PRESETS.some(
      p => p.name === theme || p.id === theme
    );
    if (isPreset) setAiPaletteActive(false);
  }, [data.config?.theme]);

  useEffect(() => {
    if (disabled) {
      setTuneOpen(false);
    }
  }, [disabled]);

  const aiPresetInitialized = useRef(false);
  const aiPresetRef = useRef<IPalettePreset | null>(null);
  if (!aiPresetInitialized.current && config.colors?.primary) {
    aiPresetInitialized.current = true;
    aiPresetRef.current = buildAiPreset(config);
  }

  const applyConfig = useCallback(
    (next: IDesignStyleConfig) => {
      onChange?.({ config: next });
    },
    [onChange]
  );

  const applyPalette = useCallback(
    (preset: IPalettePreset) => {
      setAiPaletteActive(preset.id === AI_PRESET_ID);
      applyConfig(applyPaletteToConfig(config, preset));
    },
    [applyConfig, config]
  );

  const canEdit = !disabled && Boolean(onChange);
  const canShowFineTune = Boolean(onChange);
  const themeName = config.theme || null;
  const previewTitle = config.preview_page?.title;
  const activePresetLabel = aiPaletteActive
    ? 'AI 推荐'
    : (PALETTE_PRESETS.find(p => p.name === themeName || p.id === themeName)
        ?.name ?? themeName);

  return (
    <div className='flex h-full min-h-0 flex-col'>
      <div
        ref={splitContainerRef}
        className='min-h-0 flex-1 overflow-hidden'
      >
        <ResizablePanelGroup
          direction='horizontal'
          className='h-full min-h-0'
          autoSaveId='design-style-split-left-220'
        >
          {/* Left: palette presets */}
          <ResizablePanel
            defaultSize={leftPanelSizes.defaultSize}
            minSize={leftPanelSizes.minSize}
            maxSize={leftPanelSizes.maxSize}
          >
            <div className='h-full'>
              <div className='h-full min-h-0 overflow-hidden rounded-l-[12px] rounded-r-none'>
                <div className='flex h-full min-h-0 flex-col'>
                  <div className='shrink-0 flex items-center gap-2 px-4 pt-3 pb-3 text-sm text-[var(--ds-text-9)] border-none'>
                    <IconFont
                      type='icon-tiaoseban'
                      className='text-[var(--ds-text-7)]'
                    />
                    <EllipsisTooltip>{t.color_card}</EllipsisTooltip>
                  </div>
                  <PresetThemesNav
                    activeThemeName={themeName}
                    aiPreset={aiPresetRef.current ?? undefined}
                    aiPaletteActive={aiPaletteActive}
                    onApply={canEdit ? applyPalette : () => {}}
                    disabled={!canEdit}
                  />
                </div>
              </div>
            </div>
          </ResizablePanel>

          <ResizableHandle className='design-panel-resize-handle' />

          {/* Right: preview + (overlay) fine-tune */}
          <ResizablePanel
            defaultSize={leftPanelSizes.rightDefaultSize}
            minSize={leftPanelSizes.rightMinSize}
          >
            <div className='relative h-full flex flex-col bg-white rounded-e-2xl overflow-hidden'>
              {/* Preview toolbar */}
              <DesignPanelHeader>
                <div className='flex items-center gap-3 min-w-0'>
                  <DesignPanelTitle className='shrink-0'>
                    {t.prototype_preview}
                  </DesignPanelTitle>
                  {previewTitle && (
                    <span className='text-xs text-gray-500 truncate'>
                      {previewTitle}
                      {activePresetLabel && ` · ${activePresetLabel}`}
                    </span>
                  )}
                </div>
                <div className='flex items-center gap-2 shrink-0'>
                  {onRefresh && (
                    <Button
                      type='button'
                      variant='outline'
                      size='sm'
                      onClick={() => onRefresh()}
                      title={t.design_preview_reload_title}
                    >
                      <IconFont type='icon-line-operation-refresh' />
                      {t.design_preview_refresh}
                    </Button>
                  )}
                  {canShowFineTune && (
                    <Button
                      type='button'
                      variant='outline'
                      size='sm'
                      onClick={() => setTuneOpen(o => !o)}
                      disabled={!canEdit}
                    >
                      <IconFont type='icon-line-tool-config' />
                      {t.design_fine_tuning}
                    </Button>
                  )}
                </div>
              </DesignPanelHeader>

              {/* Preview body — iframe rendering the AI-generated prototype */}
              <div className='flex-1 min-h-0 overflow-hidden bg-[var(--ds-bg-gary-default)]'>
                <PreviewFrame config={config} />
              </div>

              {/* Fine-tune overlay */}
              {canEdit && tuneOpen && (
                <FineTuneOverlay
                  config={config}
                  onChange={applyConfig}
                  onClose={() => setTuneOpen(false)}
                  onSaveAndRegenerate={onSaveAndRegenerate}
                  saveAndRegenerateDisabled={disabled}
                  openSections={fineTuneOpenSections}
                  onOpenSectionsChange={setFineTuneOpenSections}
                  activeColorKey={fineTuneActiveColor}
                  onActiveColorKeyChange={setFineTuneActiveColor}
                />
              )}
            </div>
          </ResizablePanel>
        </ResizablePanelGroup>
      </div>
    </div>
  );
};

export { PALETTE_PRESETS };
