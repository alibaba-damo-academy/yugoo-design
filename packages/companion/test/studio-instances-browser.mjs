/** Real browser + isolated Companion storage. No native Agent execution claimed. */
import assert from 'node:assert/strict'
import { mkdtemp, mkdir, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { randomUUID } from 'node:crypto'
import { chromium } from 'playwright'
import { DesignProjectManager } from '../../core/lib/index.js'
import { startCompanion } from '../src/server.mjs'

const root = await mkdtemp(join(tmpdir(), 'studio-instance-browser-'))
let server, browser
try {
  const projectRoot = join(root, 'project'), stateRoot = join(root, 'state')
  await mkdir(stateRoot)
  await new DesignProjectManager().create({ root: projectRoot, name: 'Studio CRUD check', kit: { name: 'web_app', version: '1.0' }, knowledge: { provider: 'ladybug-wasm' } })
  server = await startCompanion({ projectRoot, stateRoot, kitRoot: resolve('packages/skills-web-app'), staticRoot: resolve('packages/companion/dist'),
    knowledgeAutoRefresh: false, embedding: { provider: 'disabled' },
    connection: { host: 'claude-code', threadId: randomUUID(), send: async () => { throw Error('This CRUD check must not dispatch an Agent') } }, host: 'claude-code' })
  browser = await chromium.launch({ headless: true })
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  page.setDefaultTimeout(15000)
  page.on('dialog', dialog => dialog.accept())
  await page.goto(`${server.origin}/?view=studio#${server.token}`)
  await page.getByRole('button', { name: '中文', exact: true }).click()
  await page.getByRole('button', { name: '打开 →', exact: true }).first().click()
  await page.getByRole('tab', { name: 'Kit 文件', exact: true }).waitFor()
  await page.locator('.ygd-studio-file-tree button[title="mindset.md"]').waitFor()
  await page.locator('.ygd-studio-doc-toolbar').getByRole('button', { name: '原文', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('[aria-label="Kit file source"]')?.textContent.includes('<design_skills>'))
  assert.equal(await page.locator('.ygd-studio-file-tree button[title="kit.yaml"]').count(), 1, 'Kit view exposes its own mount manifest')
  assert.equal(await page.locator('.ygd-studio-file-tree button[title="skills"], .ygd-studio-file-tree button[title="bundles"]').count(), 0, 'Kit file tree does not own Bundle directories')
  await page.screenshot({ path: '/tmp/studio-kit-files-check.png' })
  const kitFrame = await page.locator('.ygd-studio-workspace-body').boundingBox()
  await page.getByRole('tab', { name: /^Bundles/ }).click()
  await page.getByRole('button', { name: '打开 →', exact: true }).first().click()
  await page.locator('.ygd-studio-bundle-main .ygd-studio-workspace-body').waitFor()
  const bundleFrame = await page.locator('.ygd-studio-workspace-body').boundingBox()
  assert.equal(kitFrame.x, bundleFrame.x, 'Kit and Bundle file frames share the same left edge')
  assert.equal(kitFrame.width, bundleFrame.width, 'Kit and Bundle file frames have equal width')
  await page.getByRole('button', { name: '返回', exact: true }).click()
  await page.getByRole('button', { name: '返回', exact: true }).click()
  await page.getByRole('button', { name: '复制', exact: true }).first().click()
  const instance = page.locator('.ygd-studio-instance')
  await instance.locator('textarea').waitFor()
  const header = instance.locator('header').first()
  assert.equal(await header.locator('details').count(), 0)
  const back = await header.getByRole('button', { name: '返回', exact: true }).boundingBox()
  const copy = await header.getByRole('button', { name: '复制', exact: true }).boundingBox()
  const remove = await header.getByRole('button', { name: '删除', exact: true }).boundingBox()
  assert.ok(back.x < copy.x && copy.x < remove.x, 'Back left; Copy/Delete right')
  await header.getByRole('button', { name: '重命名', exact: true }).click()
  await page.getByRole('textbox', { name: '副本名称' }).fill('Studio Kit 验证')
  await page.getByRole('textbox', { name: '副本名称' }).press('Enter')
  await page.getByRole('heading', { name: 'Studio Kit 验证', exact: true }).waitFor()
  const editor = instance.locator('textarea')
  const original = await editor.inputValue()
  assert.ok(original.includes('design_skills'), 'Kit source retains mounted skill XML')
  await editor.fill(original + '\n<!-- browser persistence check -->\n')
  await instance.getByRole('button', { name: '保存', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.ygd-studio-instance .ygd-studio-doc-footer')?.textContent.includes('已保存'))
  await page.reload()
  await page.locator('article').filter({ has: page.getByRole('heading', { name: 'Studio Kit 验证', exact: true }) }).getByRole('button', { name: '打开 →', exact: true }).click()
  await instance.locator('textarea').waitFor()
  assert.ok((await instance.locator('textarea').inputValue()).includes('browser persistence check'))
  await instance.getByRole('button', { name: '挂载管理', exact: true }).click()
  const mounts = instance.getByRole('region', { name: '挂载管理', exact: true })
  const checkboxes = mounts.getByRole('checkbox')
  const total = await checkboxes.count()
  assert.ok(total > 1)
  const removedName = await checkboxes.last().locator('..').textContent()
  await checkboxes.last().uncheck()
  await mounts.getByRole('button', { name: '保存挂载', exact: true }).click()
  await mounts.waitFor({ state: 'detached' })
  await instance.getByRole('button', { name: '挂载管理', exact: true }).click()
  assert.equal(await mounts.getByRole('checkbox').last().isChecked(), false, 'unmount persists and candidate remains selectable')
  assert.equal(await mounts.getByRole('checkbox').last().locator('..').textContent(), removedName)
  await mounts.getByRole('checkbox').last().check()
  await mounts.getByRole('button', { name: '保存挂载', exact: true }).click()
  await mounts.waitFor({ state: 'detached' })
  await page.screenshot({ path: '/tmp/studio-instance-toolbar-check.png' })
  let releasePreview
  const previewGate = new Promise(resolve => { releasePreview = resolve })
  await page.route('**/api', async route => {
    if (route.request().postData()?.includes('studioInstancePreview')) await previewGate
    await route.continue()
  })
  await instance.getByRole('button', { name: '面板预览', exact: true }).click()
  await instance.locator('.ygd-studio-spinner').waitFor()
  assert.equal(await instance.locator('.ygd-studio-spinner').evaluate(element => getComputedStyle(element, '::before').animationName), 'ygd-studio-progress')
  releasePreview()
  await instance.locator('.ygd-studio-spinner').waitFor({ state: 'detached' })
  assert.equal(await instance.getByRole('alert').count(), 0)
  await instance.getByRole('button', { name: '复制', exact: true }).click()
  await page.getByRole('heading', { name: 'Studio Kit 验证 副本', exact: true }).waitFor()
  await instance.getByRole('button', { name: '删除', exact: true }).click()
  await instance.waitFor({ state: 'detached' })
  await page.reload()
  await page.getByRole('heading', { name: 'Studio Kit 验证', exact: true }).waitFor()
  assert.equal(await page.getByRole('heading', { name: 'Studio Kit 验证 副本', exact: true }).count(), 0)
  await page.locator('article').filter({ has: page.getByRole('heading', { name: 'Studio Kit 验证', exact: true }) }).getByRole('button', { name: '打开 →', exact: true }).click()
  await instance.getByRole('button', { name: '删除', exact: true }).click()
  await instance.waitFor({ state: 'detached' })
  console.log('PASS browser Kit copy/rename/edit/reload/copy/delete, direct toolbar placement, mounted XML preservation. No Agent invocation.')
} finally {
  await browser?.close()
  await server?.close()
  await rm(root, { recursive: true, force: true })
}
